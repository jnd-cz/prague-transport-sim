const listeners = [];
const browserLang = (navigator.language || '').toLowerCase().startsWith('cs') ? 'cs' : 'en';
let lang = browserLang;
try { lang = localStorage.getItem('tram.lang') || browserLang; } catch { /* storage unavailable */ }
if (!DICT[lang]) lang = 'en';

export function t(key, vars = {}) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function getLang() { return lang; }

let currentLine = '22';
export function setLine(l) { currentLine = l; }

export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem('tram.lang', l); } catch { /* storage unavailable */ }
  applyStatic();
  for (const f of listeners) f(l);
}

export function onLangChange(f) { listeners.push(f); }

// elements with data-i18n="key" get their innerHTML translated
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('doc.title', { line: currentLine });
  for (const el of document.querySelectorAll('[data-i18n]')) el.innerHTML = t(el.dataset.i18n);
}
